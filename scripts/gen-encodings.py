# Generates src/text_tables.bats: python3 scripts/gen-encodings.py
# The single-byte encodings a content document may declare (quire#436): each
# one's 128 code points for the bytes 128 to 255 (4 hex digits each; U+FFFD
# where the encoding has none), and the labels that name it. The labels are
# the WHATWG Encoding Standard's, which is what a browser does with a label:
# iso-8859-1, latin1 and us-ascii all name windows-1252.
import sys

ENCODINGS = [
  # (constructor, python codec, labels)
  ("Cp1250", "cp1250", ["windows-1250", "cp1250", "x-cp1250"]),
  ("Cp1251", "cp1251", ["windows-1251", "cp1251", "x-cp1251"]),
  ("Cp1252", "cp1252", ["windows-1252", "cp1252", "x-cp1252", "iso-8859-1", "iso8859-1", "iso_8859-1", "iso88591", "latin1", "latin-1", "l1", "us-ascii", "ascii", "ansi_x3.4-1968"]),
  ("Cp1253", "cp1253", ["windows-1253", "cp1253", "x-cp1253"]),
  ("Cp1254", "cp1254", ["windows-1254", "cp1254", "x-cp1254", "iso-8859-9", "iso8859-9", "latin5", "l5"]),
  ("Cp1255", "cp1255", ["windows-1255", "cp1255", "x-cp1255"]),
  ("Cp1256", "cp1256", ["windows-1256", "cp1256", "x-cp1256"]),
  ("Cp1257", "cp1257", ["windows-1257", "cp1257", "x-cp1257"]),
  ("Iso88592", "iso8859_2", ["iso-8859-2", "iso8859-2", "iso_8859-2", "latin2", "l2"]),
  ("Iso88595", "iso8859_5", ["iso-8859-5", "iso8859-5", "iso_8859-5", "cyrillic"]),
  ("Iso88597", "iso8859_7", ["iso-8859-7", "iso8859-7", "iso_8859-7", "greek", "greek8"]),
  ("Iso88598", "iso8859_8", ["iso-8859-8", "iso8859-8", "iso_8859-8", "iso-8859-8-i", "hebrew", "logical", "visual"]),
  ("Iso885915", "iso8859_15", ["iso-8859-15", "iso8859-15", "iso_8859-15", "latin9", "l9"]),
  ("Koi8r", "koi8_r", ["koi8-r", "koi8", "koi8_r"]),
]
UTF8 = ["utf-8", "utf8", "unicode-1-1-utf-8"]
UTF16 = ["utf-16", "utf16", "utf-16le", "utf-16be", "ucs-2", "unicode", "iso-10646-ucs-2"]

def table(codec):
    text = bytes(range(128, 256)).decode(codec, errors="replace")
    return "".join("%04x" % ord(c) for c in text)

out = []
w = out.append
w("(* text_tables -- the single-byte encodings a document may declare, and the labels that name\n   them. GENERATED by scripts/gen-encodings.py: do not edit. *)\n")
w('#include "share/atspre_staload.hats"\n#use array as A\n')
w("(* How a document's bytes are read: UTF-8, UTF-16 (either order), one of the single-byte encodings, or an\n   encoding Quire has no table for *)")
ctors = ["SrcUtf8", "SrcUtf16Le", "SrcUtf16Be", "SrcUnsupported"] + ["Src" + e[0] for e in ENCODINGS]
w("#pub datatype text_source = " + " | ".join(ctors) + "\n")
w("fn _hex_value (digit: int): int =\n  if digit >= 97 then digit - 87 else digit - 48\n")
w("(* The code point for the byte at index (0 to 127: the bytes 128 to 255) of a table of 4 hex digits each *)")
w("fn _table_code {n:nat} (table: string n, index: int): int = let\n  val k = g1ofg0(index)\n  val length = g1u2i(string1_length(table))\nin\n  if k < 0 then 65533\n  else if 4 * k + 3 >= length then 65533\n  else _hex_value(char2int0(string_get_at(table, 4 * k))) * 4096 + _hex_value(char2int0(string_get_at(table, 4 * k + 1))) * 256\n       + _hex_value(char2int0(string_get_at(table, 4 * k + 2))) * 16 + _hex_value(char2int0(string_get_at(table, 4 * k + 3)))\nend\n")
w("(* The code point a byte of 128 to 255 stands for in a single-byte source; U+FFFD for any other source *)")
w("#pub fn text_table_code (source: text_source, byte_value: int): int")
w("")
w("implement text_table_code (source, byte_value) = let\n  val index = byte_value - 128\nin\n  case+ source of")
for c, codec, labels in ENCODINGS:
    w(f'  | Src{c}() => _table_code("{table(codec)}", index)')
w("  | SrcUtf8() => 65533\n  | SrcUtf16Le() => 65533\n  | SrcUtf16Be() => 65533\n  | SrcUnsupported() => 65533\nend\n")
w("(* Whether data[offset, offset + span_len), in lower case, is text (lower case), from position *)")
w("""fun _label_from {l:agz}{n:pos}{offset,span_len:nat | offset + span_len <= n}{text_len:nat}{position:nat | position <= text_len} .<text_len - position>.
  (data: !$A.borrow(byte, l, n), offset: int offset, span_len: int span_len, text: string text_len, text_len: int text_len, position: int position): bool =
  if position >= text_len then true
  else if position >= span_len then false
  else let
    val letter = byte2int0($A.read<byte>(data, offset + position))
    val letter = (if letter >= 65 then (if letter <= 90 then letter + 32 else letter) else letter): int
  in if letter <> char2int0(string_get_at(text, position)) then false else _label_from(data, offset, span_len, text, text_len, position + 1) end

fn _label_is {l:agz}{n:pos}{offset,span_len:nat | offset + span_len <= n}{text_len:nat}
  (data: !$A.borrow(byte, l, n), offset: int offset, span_len: int span_len, text: string text_len): bool = let
  val text_len = g1u2i(string1_length(text))
in if span_len <> text_len then false else _label_from(data, offset, span_len, text, text_len, 0) end
""")
w("(* The encoding a label names (an XML declaration's encoding=\"...\"), in any case. A UTF-16 label names UTF-16\n   little endian: the order of a document is its byte order mark's, and a document that is bytes of text\n   and says UTF-16 is read as UTF-8 (text_encoding) *)")
w("#pub fn text_source_of_label {l:agz}{n:pos}{offset,span_len:nat | offset + span_len <= n}\n  (data: !$A.borrow(byte, l, n), offset: int offset, span_len: int span_len): text_source")
w("")
w("implement text_source_of_label (data, offset, span_len) =")
cond = []
for label in UTF8: cond.append((label, "SrcUtf8"))
for label in UTF16: cond.append((label, "SrcUtf16Le"))
for c, codec, labels in ENCODINGS:
    for label in labels: cond.append((label, "Src" + c))
first = True
for label, c in cond:
    w(("  " if first else "  else ") + f'if _label_is(data, offset, span_len, "{label}") then {c}()')
    first = False
w("  else SrcUnsupported()")
open("src/text_tables.bats", "w").write("\n".join(out) + "\n")

# Generates src/text_labels.bats: the same labels as a table the proofs read (quire#845). Entry k is the
# k-th label tried by text_source_of_label above.
assert len(set(label for label, c in cond)) == len(cond), "a label is listed twice"
def source_term(constructor):
    # the static source of a text_source constructor
    if constructor == "SrcUtf8": return "SrcUtf8()"
    if constructor == "SrcUtf16Le": return "SrcUtf16(LittleEndian())"
    if constructor == "SrcUtf16Be": return "SrcUtf16(BigEndian())"
    if constructor == "SrcUnsupported": return "SrcUnsupported()"
    return "SrcTable(" + constructor[3:] + "())"
label_names = ["Utf8", "Utf16Le", "Utf16Be", "Unsupported"] + [e[0] for e in ENCODINGS]
label_source_terms = [source_term("SrcUtf8"), source_term("SrcUtf16Le"), source_term("SrcUtf16Be"), source_term("SrcUnsupported")] + [source_term("Src" + e[0]) for e in ENCODINGS]
lab = []
v = lab.append
v("(* text_labels -- the labels that name an encoding, as the table the proofs of text_relation read.\n   GENERATED by scripts/gen-encodings.py: do not edit. Keyword: text-encoding relation. *)\n")
v("#target wasm begin\n")
v('#include "share/atspre_staload.hats"\n')
v('staload "bytes.sats"\n')
v("(* The single-byte encodings Quire has a table for *)")
v("#pub datasort codepage = " + " | ".join(f"{e[0]} of ()" for e in ENCODINGS) + "\n")
v("(* The order of the bytes of a UTF-16 unit *)")
v("#pub datasort byteorder = LittleEndian of () | BigEndian of ()\n")
v("(* How a document's bytes are read: UTF-8, UTF-16 (either order), an encoding Quire has no table for, or one of the single-byte encodings *)")
v("#pub datasort tsrc = SrcUtf8 of () | SrcUtf16 of (byteorder) | SrcUnsupported of () | SrcTable of (codepage)\n")
v("(* EQSRC(first, second): two sources are one *)")
v("#pub dataprop EQSRC(tsrc, tsrc) =\n  | {same:tsrc} EQSRC_refl(same, same)\n")
v("(* The number of labels (the entries 0 to LABEL_COUNT - 1) *)")
v(f"#pub stadef LABEL_COUNT = {len(cond)}\n")
v("(* LABEL_COUNT, as a value *)")
v("#pub fn text_label_total (): int(LABEL_COUNT)\n")
v(f"implement text_label_total () = {len(cond)}\n")
v("(* LABELENTRY(index, label, source): the index-th label tried is the byte string label (lower case), and it names the source *)")
v("#pub dataprop LABELENTRY(int, bytes, tsrc) =")
def octets(text):
    out_text = "bnil()"
    for ch in reversed(text):
        out_text = f"bcons({ord(ch)}, {out_text})"
    return out_text
entry_source = []
for index, (label, c) in enumerate(cond):
    term = source_term(c)
    entry_source.append(term)
    v(f"  | LABELENTRY_{index}({index}, {octets(label)}, {term})")
v("")
v("(* An entry is one label and one source *)")
v("#pub prfun entry_functional {index:nat}{first_label,second_label:bytes}{first_source,second_source:tsrc}\n  (LABELENTRY(index, first_label, first_source), LABELENTRY(index, second_label, second_source)): (EQB(first_label, second_label), EQSRC(first_source, second_source))\n")
v("primplement entry_functional {index}{first_label,second_label}{first_source,second_source} (one, other) =\n  case+ one of")
for index in range(len(cond)):
    v(f"  | LABELENTRY_{index}() => (case+ other of LABELENTRY_{index}() => (EQB_refl(), EQSRC_refl()))")
v("")
v("(* A label is one entry *)")
v("#pub prfun entry_label_injective {first_index,second_index:nat}{label:bytes}{first_source,second_source:tsrc}\n  (LABELENTRY(first_index, label, first_source), LABELENTRY(second_index, label, second_source)): EQI(first_index, second_index)\n")
v("primplement entry_label_injective {first_index,second_index}{label}{first_source,second_source} (one, other) =\n  case+ one of")
for index in range(len(cond)):
    v(f"  | LABELENTRY_{index}() => (case+ other of LABELENTRY_{index}() => EQI_refl())")
v("")
v("(* Every entry is below LABEL_COUNT *)")
v("#pub prfun entry_below_count {index:nat}{label:bytes}{source:tsrc} (LABELENTRY(index, label, source)): [index < LABEL_COUNT] void\n")
v("primplement entry_below_count {index}{label}{source} (entry) =\n  case+ entry of")
for index in range(len(cond)):
    v(f"  | LABELENTRY_{index}() => ()")
v("")
v("(* The source of a label, as a value *)")
v("#pub datatype label_source(tsrc) = " + " | ".join(f"Label{name}({term})" for name, term in zip(label_names, label_source_terms)) + "\n")
v("(* The index-th label, as a list of its bytes, with the source it names *)")
v("#pub fn text_entry_label {index:nat | index < LABEL_COUNT} (index: int index)\n  : [label:bytes][source:tsrc][count:nat] (LABELENTRY(index, label, source) | blist(label, count), label_source(source))\n")
v("implement text_entry_label {index} (index) =")
def leaf(i):
    label, c = cond[i]
    body = "blist_nil()"
    for ch in reversed(label):
        body = f"blist_cons({ord(ch)}, {body})"
    return f"(LABELENTRY_{i}() | {body}, Label{c[3:]}())"
def tree(lo, hi, depth):
    pad = "  " * depth
    if hi - lo == 1:
        return pad + leaf(lo)
    mid = (lo + hi) // 2
    return f"{pad}if index < {mid} then\n" + tree(lo, mid, depth + 1) + f"\n{pad}else\n" + tree(mid, hi, depth + 1)
v(tree(0, len(cond), 1))
v("\nend")
open("src/text_labels.bats", "w").write("\n".join(lab) + "\n")

# Generates src/text_codes.bats: the code point each byte of 128 to 255 stands for in each single-byte encoding, as a
# relation the proofs read (quire#845). It is made from the same tables as text_tables.bats above.
cod = []
c = cod.append
c("(* text_codes -- the code points of the single-byte encodings, as the relation the proofs of text_relation read.\n   GENERATED by scripts/gen-encodings.py: do not edit. Keyword: text-encoding relation. *)\n")
c("#target wasm begin\n")
c('#include "share/atspre_staload.hats"\n')
c('staload "text_labels.sats"\n')
c("(* One encoding's table: PAGEAT_<page>(byte, code point) says the byte of 128 to 255 stands for the code point (65533 where the\n   encoding has none). A table of its own for each encoding, so that the proof that a byte has one code point reads 128\n   constructors for each encoding and not 1792 for every clause (patsopt's memory grows with the square of the constructors a\n   case is checked against, quire#845, keyword: text-encoding relation) *)")
codes = {}
for number, (name, codec, labels) in enumerate(ENCODINGS):
    text = bytes(range(128, 256)).decode(codec, errors="replace")
    codes[name] = [ord(ch) for ch in text]
    c(f"#pub dataprop PAGEAT_{name}(int, int) =")
    for index, point in enumerate(codes[name]):
        c(f"  | PAGEAT_{name}_{128 + index}(%d, %d)" % (128 + index, point))
    c("")
c("(* TABLEAT(page, byte, code point): in the single-byte encoding page, the byte of 128 to 255 stands for the code point\n   (65533 where the encoding has none) *)")
c("#pub dataprop TABLEAT(codepage, int, int) =")
for name, codec, labels in ENCODINGS:
    c(f"  | {{byte,point:int}} TABLEAT_{name}(%s(), byte, point) of PAGEAT_{name}(byte, point)" % name)
c("")
for name, codec, labels in ENCODINGS:
    c(f"prfn _pageat_{name.lower()}_functional {{byte,first,second:int}}\n  (one: PAGEAT_{name}(byte, first), other: PAGEAT_{name}(byte, second)): [first == second] void =\n  case+ one of")
    for index in range(128):
        c(f"  | PAGEAT_{name}_{128 + index}() => (case+ other of PAGEAT_{name}_{128 + index}() => ())")
    c("")
c("(* A byte stands for one code point in an encoding *)")
c("#pub prfun tableat_functional {page:codepage}{byte:int}{first,second:int}\n  (TABLEAT(page, byte, first), TABLEAT(page, byte, second)): [first == second] void\n")
c("primplement tableat_functional {page}{byte}{first,second} (one, other) =\n  case+ one of")
for name, codec, labels in ENCODINGS:
    c(f"  | TABLEAT_{name}(one_page) => (case+ other of TABLEAT_{name}(other_page) => _pageat_{name.lower()}_functional(one_page, other_page))")
c("")
def table_tree(name, lo, hi, depth):
    pad = "  " * depth
    if hi - lo == 1:
        return f"{pad}(TABLEAT_{name}(PAGEAT_{name}_{lo}()) | {codes[name][lo - 128]})"
    mid = (lo + hi) // 2
    return f"{pad}if byte < {mid} then\n" + table_tree(name, lo, mid, depth + 1) + f"\n{pad}else\n" + table_tree(name, mid, hi, depth + 1)
for number, (name, codec, labels) in enumerate(ENCODINGS):
    c(f"fn _table_{name.lower()} {{byte:int | 128 <= byte; byte < 256}} (byte: int byte)\n  : [point:int | 0 <= point; point < 65536] (TABLEAT({name}(), byte, point) | int point) =")
    c(table_tree(name, 128, 256, 1))
    c("")
c("(* The code point a byte of 128 to 255 stands for in a single-byte source, with the proof of it *)")
c("#pub fn text_table_point {page:codepage}{byte:int | 128 <= byte; byte < 256} (source: label_source(SrcTable(page)), byte: int byte)\n  : [point:int | 0 <= point; point < 65536] (TABLEAT(page, byte, point) | int point)\n")
c("implement text_table_point {page}{byte} (source, byte) =\n  case+ source of")
for number, (name, codec, labels) in enumerate(ENCODINGS):
    c(f"  | Label{name}() => _table_{name.lower()}(byte)")
c("\nend")
open("src/text_codes.bats", "w").write("\n".join(cod) + "\n")
