    def test_qsweep_reads_the_library_repositories_before_it_prints_the_next_line(self):
        text = read_root('.claude', 'skills', 'sweep', 'qsweep')
        loop = re.search(r'^for r in ([a-z0-9 -]+); do$', text, re.M)
