class PullRequestBody(unittest.TestCase):
    def findings(self, body, head=HEAD):
        return gl.lint_pr_body(body, head, PHRASES)

    def test_a_good_body_passes(self):
        self.assertEqual(self.findings(GOOD_BODY), [])

    def test_the_first_line_is_fixes(self):
        self.assertTrue(self.findings(GOOD_BODY.replace('Fixes #751', 'Refs #751')))

    def test_one_ticket_one_pr(self):
        found = self.findings(GOOD_BODY.replace('Fixes #751', 'Fixes #751\n\nFixes #752'))
        self.assertTrue(any('one ticket, one PR' in line for line in found), found)
        self.assertEqual(self.findings(GOOD_BODY.replace('Fixes #751', 'Fixes #751\n\nFixes #751')), [])

    def test_a_body_for_an_older_head_is_refused(self):
        found = self.findings(GOOD_BODY, OTHER)
        self.assertTrue(any('describes head' in line for line in found), found)

    def test_a_body_without_a_head_line_is_refused(self):
        self.assertTrue(self.findings(GOOD_BODY.replace(f'Head: {HEAD}\n', '')))

    def test_evidence_is_a_heading_and_a_command_with_its_output(self):
        self.assertTrue(self.findings(GOOD_BODY.replace('## Evidence', '## Notes')))
        self.assertTrue(self.findings(GOOD_BODY.replace('$ python3', 'python3')))

    def test_the_generated_line_ends_the_body(self):
        self.assertTrue(self.findings(GOOD_BODY.replace('🤖 Generated with [Claude Code](https://claude.ai/code)\n', '')))

    def test_the_proxys_footer_closes_a_body_too(self):
        proxied = GOOD_BODY.replace('🤖 Generated with [Claude Code](https://claude.ai/code)\n', '---\n_Generated by [Claude Code](https://claude.ai/code)_\n')
        self.assertEqual(self.findings(proxied), [])

    def test_a_banned_phrase_in_a_body_is_refused(self):
        self.assertTrue(self.findings(GOOD_BODY.replace('ok: 33 phrases', 'it passed alone')))


class Review(unittest.TestCase):
    def findings(self, text, gate=False):
        return gl.lint_review(text, PHRASES, gate)

    def test_good_reviews_pass(self):
        self.assertEqual(self.findings(GOOD_REVIEW), [])
        self.assertEqual(self.findings(GATE_REVIEW), [])

    def test_the_first_line_is_exactly_the_one_form(self):
        self.assertTrue(self.findings(GOOD_REVIEW.replace('approved', 'provisional', 1)))
        self.assertTrue(self.findings(GOOD_REVIEW.replace(HEAD, 'abc1234')))
        self.assertTrue(self.findings(GOOD_REVIEW.replace('approved', 'approved.', 1)))
        self.assertTrue(self.findings('approved\n\n' + HEAD))
        self.assertEqual(self.findings(GOOD_REVIEW.replace('approved', 'changes needed', 1)), [])

    def test_qsweep_and_the_workflow_recognise_the_same_first_lines(self):
        self.assertTrue(gl.is_review_first_line(FIRST + 'approved'))
        self.assertTrue(gl.is_review_first_line(FIRST + 'changes needed'))
        self.assertTrue(gl.is_review_first_line('## Adversarial review'))
        for other in ('approved', 'changes needed', FIRST + 'maybe', 'Independent review of head ' + HEAD + ': approved'):
            self.assertFalse(gl.is_review_first_line(other), other)
        with open(os.path.join(gl.ROOT, '.claude', 'skills', 'sweep', 'qsweep'), encoding='utf-8') as handle:
            qsweep = handle.read()
        self.assertIn('Independent review \\\\(a separate reviewer agent, not the author\\\\) of head [0-9a-f]{40}: (approved|changes needed)', qsweep)
        with open(os.path.join(gl.ROOT, '.claude', 'agents', 'reviewer.md'), encoding='utf-8') as handle:
            self.assertIn('Independent review (a separate reviewer agent, not the author) of head <the 40-character head SHA>: approved', handle.read())

    def test_two_reviewed_lines_are_refused_as_bridge_200_was(self):
        found = self.findings(GATE_REVIEW.replace('Findings.', f'Reviewed: {HEAD} again'))
        self.assertTrue(any('Reviewed:' in line for line in found), found)

    def test_two_verdict_lines_and_a_dressed_verdict_are_refused(self):
        self.assertTrue(self.findings(GATE_REVIEW + 'Verdict: approved\n'))
        self.assertTrue(self.findings(GATE_REVIEW.replace('Verdict: approved', '**Verdict: approved**')))

    def test_the_gate_form_is_demanded_when_asked(self):
        self.assertTrue(self.findings(GOOD_REVIEW, gate=True))

    def test_a_review_may_quote_a_phrase_in_a_code_span(self):
        self.assertEqual(self.findings(GOOD_REVIEW.replace('The Done-when is met.', 'The body says `it passed alone`.')), [])

    def test_an_exit_clause_in_a_review_is_refused(self):
        self.assertTrue(self.findings(GOOD_REVIEW.replace('The Done-when is met.', 'Use Refs instead of Fixes.')))


class Brief(unittest.TestCase):
    TICKET = '## What\n\nx\n\n## Done when\n\nEvery row has its line.\nThe tests pass.\n\n## Not in this ticket\n\ny\n'

    def test_a_brief_that_copies_the_done_when_passes(self):
        brief = 'Do it.\n\nEvery row has its line.\nThe tests pass.\n'
        self.assertEqual(gl.lint_brief(brief, self.TICKET, PHRASES), [])

    def test_a_brief_that_restates_it_is_refused(self):
        found = gl.lint_brief('Do it. Every row has its line.', self.TICKET, PHRASES)
        self.assertTrue(any('The tests pass.' in line for line in found), found)

    def test_a_ticket_without_a_done_when_is_refused(self):
        self.assertTrue(gl.lint_brief('Do it.', '## What\n\nx\n', PHRASES))

    def test_an_exit_clause_in_a_brief_is_refused(self):
        brief = 'Every row has its line.\nThe tests pass.\nOr say what is true.'
        self.assertTrue(gl.lint_brief(brief, self.TICKET, PHRASES))


class FakeApi:
    def __init__(self, comments=()):
        self.comments, self.calls = list(comments), []

    def __call__(self, path, method='GET', fields=None):
        self.calls.append((method, path, fields))
        if method == 'GET' and path.split('?')[0].endswith('/comments'):
            page = int(path.rsplit('page=', 1)[1])
            return self.comments if page == 1 else []
        if method == 'GET' and '/pulls/' in path:
            return PULL
        return None


PULL = {'number': 5, 'head': {'sha': HEAD, 'ref': 'claude/751-agent-guidelines'}, 'user': {'login': 'moshez'}, 'body': GOOD_BODY}


class GitHub(unittest.TestCase):
    def status(self, api):
        return [call for call in api.calls if call[1].startswith('repos/o/r/statuses/')][-1][2]

    def run_event(self, name, event, api):
        return gl.github(name, event, 'o/r', api, PHRASES, 'https://run')

    def test_a_good_pull_request_gets_success_on_its_head(self):
        api = FakeApi()
        self.assertEqual(self.run_event('pull_request_target', {'pull_request': PULL}, api), [])
        self.assertEqual(self.status(api)['state'], 'success')
        self.assertIn(('POST', f'repos/o/r/statuses/{HEAD}', self.status(api)), api.calls)

    def test_a_stale_body_gets_failure_naming_the_head(self):
        api = FakeApi()
        pull = dict(PULL, head={'sha': OTHER, 'ref': 'x'})
        self.assertTrue(self.run_event('pull_request_target', {'pull_request': pull}, api))
        self.assertEqual(self.status(api)['state'], 'failure')
        self.assertIn('describes head', self.status(api)['description'])

    def test_a_bot_and_a_relock_branch_are_exempt(self):
        for pull in (dict(PULL, user={'login': 'dependabot[bot]'}, body=''), dict(PULL, head={'sha': HEAD, 'ref': 'relock/2026-10-21'}, body='')):
            api = FakeApi()
            self.assertEqual(self.run_event('pull_request_target', {'pull_request': pull}, api), [])
            self.assertEqual(self.status(api)['state'], 'success')

    def test_the_newest_trusted_review_is_linted(self):
        bad = {'author_association': 'OWNER', 'body': FIRST + 'approved\n\nUse Refs instead of Fixes.', 'html_url': 'u'}
        good = {'author_association': 'OWNER', 'body': GOOD_REVIEW, 'html_url': 'v'}
        stranger = {'author_association': 'NONE', 'body': FIRST + 'approved\nrefs instead of fixes', 'html_url': 'w'}
        api = FakeApi([good, bad, stranger])
        self.assertTrue(self.run_event('issue_comment', {'issue': {'number': 5, 'pull_request': {}}}, api))
        self.assertEqual(self.status(api)['state'], 'failure')
        api = FakeApi([bad, good, stranger])
        self.assertEqual(self.run_event('issue_comment', {'issue': {'number': 5, 'pull_request': {}}}, api), [])

    def test_a_comment_on_a_plain_issue_is_none_of_its_business(self):
        api = FakeApi()
        self.assertEqual(self.run_event('issue_comment', {'issue': {'number': 5}}, api), [])
        self.assertEqual(api.calls, [])

    def test_a_ticket_with_a_waiting_step_gets_a_comment_that_goes_when_it_is_fixed(self):
        issue = {'number': 9, 'body': 'Step 3: after a day of sessions, look.'}
        api = FakeApi()
        self.assertTrue(self.run_event('issues', {'issue': issue}, api))
        self.assertEqual([call[0] for call in api.calls if call[0] != 'GET'], ['POST'])
        marked = {'id': 77, 'body': gl.MARKER + '\nold'}
        api = FakeApi([marked])
        self.assertTrue(self.run_event('issues', {'issue': issue}, api))
        self.assertIn(('PATCH', 'repos/o/r/issues/comments/77'), [call[:2] for call in api.calls])
        quoted = dict(issue, body='| 13 | A step waits: `after a day of sessions`. | x |\nafter a day: in a row\n'.replace('after a day: in a row', '| after a day | y |'))
        self.assertEqual(self.run_event('issues', {'issue': quoted}, FakeApi()), [])
        api = FakeApi([marked])
        self.assertEqual(self.run_event('issues', {'issue': dict(issue, body='Step 3: look now.')}, api), [])
        self.assertIn(('DELETE', 'repos/o/r/issues/comments/77'), [call[:2] for call in api.calls])


