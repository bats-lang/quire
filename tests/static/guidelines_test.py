class Phrases(unittest.TestCase):
    def test_each_phrase_refuses_its_example(self):
        for scope, row, regex, reason, example in PHRASES:
            with self.subTest(regex=regex.pattern):
                self.assertTrue(regex.search(example), f'{regex.pattern} does not match {example!r}')
                found = gl.lint_text(example, 'x', PHRASES, guide=(scope == 'guide'))
                self.assertTrue(any(f'row {row}' in line for line in found), found)

    def test_text_scope_phrases_are_found_in_a_text_and_guide_scope_ones_are_not(self):
        self.assertTrue(gl.lint_text('it passed alone', 'x', PHRASES))
        self.assertEqual(gl.lint_text('No sed.', 'x', PHRASES), [])
        self.assertTrue(gl.lint_text('No sed.', 'x', PHRASES, guide=True))

    def test_a_guideline_quotes_a_phrase_in_a_code_span_or_a_block(self):
        self.assertEqual(gl.lint_text('Never write `it passed alone`.', 'x', PHRASES, guide=True), [])
        self.assertEqual(gl.lint_text('```\nit passed alone\n```\n', 'x', PHRASES, guide=True), [])
        self.assertTrue(gl.lint_text('it passed alone', 'x', PHRASES, guide=True))
        self.assertTrue(gl.lint_text('Never write `it passed alone`.', 'x', PHRASES))

    def test_an_area_note_is_held_to_the_guide_phrases_only(self):
        self.assertEqual(gl.lint_text('PSI cannot separate contention from none.', 'x', PHRASES, guide=True, notes=True), [])
        self.assertTrue(gl.lint_text('No sed.', 'x', PHRASES, guide=True, notes=True))

    def test_all_and_data_in_one_sentence(self):
        self.assertTrue(gl.lint_text('We measured all the data.', 'x', PHRASES))
        self.assertEqual(gl.lint_text('We measured all fixtures. The data is a sample.', 'x', PHRASES), [])

    def test_the_repository_guidelines_are_clean(self):
        self.assertEqual(gl.lint_guidelines(gl.ROOT, PHRASES), [])


class Contradictions(unittest.TestCase):
    def test_each_pair_is_found_on_its_examples_and_not_on_one_alone(self):
        pairs = gl.load_contradictions()
        self.assertGreaterEqual(len(pairs), 4)
        for first, second, example_first, example_second, _reason in pairs:
            with self.subTest(pair=first.pattern):
                self.assertTrue(first.search(example_first) and second.search(example_second))
                self.assertTrue(gl.lint_contradictions({'a.md': example_first, 'b.md': example_second}, pairs))
                self.assertFalse(any(first.pattern in line and second.pattern in line
                                     for line in gl.lint_contradictions({'a.md': example_first}, pairs)))

    def test_a_pair_in_a_code_span_is_a_quotation(self):
        pairs = gl.load_contradictions()
        self.assertEqual(gl.lint_contradictions({'a.md': '`left to CI and said in the PR`', 'b.md': '`is not reported as a gap`'}, pairs), [])

    def test_the_exit_clause_without_its_tail_is_refused(self):
        for text in ('change Fixes #368 to Refs #368', 'open it as Refs', 'use Refs'):
            self.assertTrue(gl.lint_text(text, 'x', PHRASES), text)


