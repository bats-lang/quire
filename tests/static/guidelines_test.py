class GitHub(unittest.TestCase):
    def status(self, api):
        return [call for call in api.calls if call[1].startswith('repos/o/r/statuses/')][-1][2]

    def run_event(self, name, event, api):
        return gl.github(name, event, 'o/r', api, PHRASES, 'https://run')

    def test_a_good_pull_request_gets_success_on_its_head(self):
        api = FakeApi()
        self.assertEqual(self.run_event('pull_request_target', {'pull_request': PULL}, api), [])
        self.assertEqual(self.status(api)['state'], 'success')
        self.assertIn(('POST', f'repos/o/r/statuses/{HEAD}', self.status(api)), api.calls)

    def test_a_stale_body_gets_failure_naming_the_head(self):
        api = FakeApi()
        pull = dict(PULL, head={'sha': OTHER, 'ref': 'x'})
        self.assertTrue(self.run_event('pull_request_target', {'pull_request': pull}, api))
        self.assertEqual(self.status(api)['state'], 'failure')
        self.assertIn('describes head', self.status(api)['description'])

    def test_a_bot_and_a_relock_branch_are_exempt(self):
        for pull in (dict(PULL, user={'login': 'dependabot[bot]'}, body=''), dict(PULL, head={'sha': HEAD, 'ref': 'relock/2026-10-21'}, body='')):
            api = FakeApi()
            self.assertEqual(self.run_event('pull_request_target', {'pull_request': pull}, api), [])
            self.assertEqual(self.status(api)['state'], 'success')

    def test_the_newest_trusted_review_is_linted(self):
        bad = {'author_association': 'OWNER', 'body': FIRST + 'approved\n\nUse Refs instead of Fixes.', 'html_url': 'u'}
        good = {'author_association': 'OWNER', 'body': GOOD_REVIEW, 'html_url': 'v'}
        stranger = {'author_association': 'NONE', 'body': FIRST + 'approved\nrefs instead of fixes', 'html_url': 'w'}
        api = FakeApi([good, bad, stranger])
        self.assertTrue(self.run_event('issue_comment', {'issue': {'number': 5, 'pull_request': {}}}, api))
        self.assertEqual(self.status(api)['state'], 'failure')
        api = FakeApi([bad, good, stranger])
        self.assertEqual(self.run_event('issue_comment', {'issue': {'number': 5, 'pull_request': {}}}, api), [])

    def test_a_comment_on_a_plain_issue_is_none_of_its_business(self):
        api = FakeApi()
        self.assertEqual(self.run_event('issue_comment', {'issue': {'number': 5}}, api), [])
        self.assertEqual(api.calls, [])

    def test_a_ticket_with_a_waiting_step_gets_a_comment_that_goes_when_it_is_fixed(self):
        issue = {'number': 9, 'body': 'Step 3: after a day of sessions, look.'}
        api = FakeApi()
        self.assertTrue(self.run_event('issues', {'issue': issue}, api))
        self.assertEqual([call[0] for call in api.calls if call[0] != 'GET'], ['POST'])
        marked = {'id': 77, 'body': gl.MARKER + '\nold'}
        api = FakeApi([marked])
        self.assertTrue(self.run_event('issues', {'issue': issue}, api))
        self.assertIn(('PATCH', 'repos/o/r/issues/comments/77'), [call[:2] for call in api.calls])
        quoted = dict(issue, body='| 13 | A step waits: `after a day of sessions`. | x |\n')
        self.assertEqual(self.run_event('issues', {'issue': quoted}, FakeApi()), [])
        plain = dict(issue, body='| 13 | A step waits after a day of sessions. | x |\n')
        self.assertTrue(self.run_event('issues', {'issue': plain}, FakeApi()))
        api = FakeApi([marked])
        self.assertEqual(self.run_event('issues', {'issue': dict(issue, body='Step 3: look now.')}, api), [])
        self.assertIn(('DELETE', 'repos/o/r/issues/comments/77'), [call[:2] for call in api.calls])


