def sed_command_lines(text):
    """The numbers of the lines of a shell or YAML text that run sed as a command (quire#751)."""
    found = []
    for number, line in enumerate(text.splitlines(), 1):
        if re.search(r'(^|[\s|;&(`]|\$\()sed(\s|$)', shell_code_of(line)):
            found.append(number)
    return found


def shell_code_of(line):
    """The part of a line the shell would run: the text of a quoted string is blanked, except what a
    command substitution inside a double quote runs (`$(...)` and backticks), and a comment is cut.
    One line at a time: a string that goes on over the next line is not followed."""
    code = []
    states = ['code']  # 'code', 'double', 'single', 'substitution', 'backtick', 'group'
    index = 0
    while index < len(line):
        char, state = line[index], states[-1]
        if state == 'single':
            if char == "'":
                states.pop()
            index += 1
            continue
        if char == '\\':
            index += 2
            continue
        if state == 'double' and char == '"':
            states.pop()
            index += 1
            continue
        if state == 'double' and char not in '`$':
            index += 1
            continue
        if line.startswith('$(', index):
            states.append('substitution')
            code.append('$(')
            index += 2
            continue
        if char == '`':
            if state == 'backtick':
                states.pop()
            else:
                states.append('backtick')
            code.append(char)
        elif state == 'double':
            pass  # a `$` that starts no substitution
        elif char == "'":
            states.append('single')
        elif char == '"':
            states.append('double')
        elif char == '(' and state in ('substitution', 'group'):
            states.append('group')
            code.append(char)
        elif char == ')' and state in ('substitution', 'group'):
            states.pop()
            code.append(char)
        elif char == '#' and state == 'code' and (not code or code[-1].isspace()):
            break
        else:
            code.append(char)
        index += 1
    return ''.join(code)


class GhRetry(unittest.TestCase):
    """gh-retry (#931): a 5xx answer of `gh api` is retried; a persistent one fails naming the call."""

    class Done:
        def __init__(self, code, out='', err=''):
            self.returncode, self.stdout, self.stderr = code, out, err

    def run_with(self, answers):
        calls, waits = [], []
        saved = gl.GH_RUN, gl.GH_SLEEP

        def fake(command):
            calls.append(command)
            return answers(len(calls))
        gl.GH_RUN, gl.GH_SLEEP = fake, waits.append
        try:
            return gl.gh_api('repos/o/r/issues/1/comments?per_page=100&page=1'), calls, waits
        finally:
            gl.GH_RUN, gl.GH_SLEEP = saved

    def test_a_502_then_success_passes(self):
        answer, calls, waits = self.run_with(lambda n: self.Done(1, '', 'gh: Server Error (HTTP 502)') if n == 1 else self.Done(0, '[1]'))
        self.assertEqual((answer, len(calls), waits), ([1], 2, [gl.GH_API_WAITS[0]]))

    def test_a_502_on_every_call_fails_naming_the_call(self):
        with self.assertRaises(SystemExit) as caught:
            self.run_with(lambda n: self.Done(1, '', 'gh: Server Error (HTTP 502)'))
        self.assertIn('gh api GET repos/o/r/issues/1/comments?per_page=100&page=1 failed', str(caught.exception))

    def test_a_502_on_every_call_is_tried_four_times_with_the_stated_waits(self):
        calls, waits = [], []
        saved = gl.GH_RUN, gl.GH_SLEEP
        gl.GH_RUN, gl.GH_SLEEP = (lambda c: (calls.append(c), self.Done(1, '', 'gh: Server Error (HTTP 502)'))[1]), waits.append
        try:
            with self.assertRaises(SystemExit):
                gl.gh_api('repos/o/r/issues/1')
        finally:
            gl.GH_RUN, gl.GH_SLEEP = saved
        self.assertEqual((len(calls), waits), (gl.GH_API_RETRIES + 1, list(gl.GH_API_WAITS)))

    def test_a_404_is_not_retried(self):
        calls = []
        with self.assertRaises(SystemExit):
            self.run_with(lambda n: (calls.append(n), self.Done(1, '', 'gh: Not Found (HTTP 404)'))[1])
        self.assertEqual(len(calls), 1)


